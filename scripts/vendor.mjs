// Copy the pinned runtime libraries from node_modules into vendor/.
// Run after changing versions in package.json:  npm install && npm run vendor
import { cpSync, mkdirSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const nm = (p) => join(root, 'node_modules', p);
const out = (p) => join(root, 'vendor', p);
const version = (pkg) => JSON.parse(readFileSync(nm(`${pkg}/package.json`), 'utf8')).version;

rmSync(out(''), { recursive: true, force: true });
mkdirSync(out('pdfjs'), { recursive: true });
mkdirSync(out('fflate'), { recursive: true });

// pdf.js: the "legacy" build supports older Safari/iOS and also runs in Node.
cpSync(nm('pdfjs-dist/legacy/build/pdf.min.mjs'), out('pdfjs/pdf.min.mjs'));
cpSync(nm('pdfjs-dist/legacy/build/pdf.worker.min.mjs'), out('pdfjs/pdf.worker.min.mjs'));
cpSync(nm('pdfjs-dist/LICENSE'), out('pdfjs/LICENSE'));

// fflate: ES module build.
cpSync(nm('fflate/esm/browser.js'), out('fflate/fflate.mjs'));
cpSync(nm('fflate/LICENSE'), out('fflate/LICENSE'));

const manifest = {
  'pdfjs-dist': version('pdfjs-dist'),
  fflate: version('fflate'),
  note: 'Generated by scripts/vendor.mjs. Do not edit vendored files by hand.',
};
writeFileSync(out('VERSIONS.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log('vendored', manifest);
